"""Write docs/tools.md: every tool the unified server can expose, with a one-line description.

Backend tools come from the pinned inventory (src/unified_cad_mcp/coverage.json); in-process tools (unified_*,
drone_*, enclosure_*, miniature_*, airframe_*) from a server built with every in-process namespace enabled.
Run: .venv/bin/python scripts/list_tools.py   (tests/test_tools_doc.py fails when the file is stale)
"""
from __future__ import annotations

import asyncio
import json
from pathlib import Path
import sys
import tempfile

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from fastmcp import Client  # noqa: E402

from unified_cad_mcp.config import AirframeConfig, Configuration  # noqa: E402
from unified_cad_mcp.server import create_server  # noqa: E402

DOC = ROOT / "docs" / "tools.md"


def first_line(text: str | None) -> str:
    return " ".join((text or "").strip().split("\n\n")[0].split())


async def render() -> str:
    with tempfile.TemporaryDirectory() as tmp:
        cfg = Configuration(project_root=tmp, drone_tools=True, backends={},
                            airframe=AirframeConfig(freecad_python="python", output_root=tmp))
        async with Client(create_server(cfg)) as client:
            local = sorted((t.name, first_line(t.description)) for t in await client.list_tools())
    inventory = json.loads((ROOT / "src/unified_cad_mcp/coverage.json").read_text(encoding="utf-8"))
    lines = ["# Tool list", "", "Generated by `scripts/list_tools.py`; do not edit by hand. Which tools a running server",
             "advertises depends on the operator config (backends, `drone_tools`, `airframe`) and on backend gates",
             "(see [coverage.md](coverage.md)). Call `unified_get_context` for the live routing and backend state.", ""]
    groups: dict[str, list] = {}
    for name, desc in local:
        groups.setdefault(name.split("_")[0], []).append((name, desc))
    for backend, data in inventory["backends"].items():
        groups[backend] = [(f"{backend}_{t['name']}", first_line(t.get("description"))) for t in data["wire"]["tools"]]
    for prefix in sorted(groups):
        lines += [f"## {prefix}_*", ""] + [f"- `{n}`: {d}" for n, d in sorted(groups[prefix])] + [""]
    return "\n".join(lines)


if __name__ == "__main__":
    DOC.write_text(asyncio.run(render()), encoding="utf-8")
    print(f"wrote {DOC}")
